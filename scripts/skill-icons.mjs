/**
 * Builds public/skills.svg: one <symbol> per Simple Icons slug listed in
 * SKILL_ICONS (src/data/types.ts), from a pinned Simple Icons release. The
 * Skills section draws them with <use href="/skills.svg#slug">, in
 * currentColor, so the logos cost nothing in the JS bundle.
 *
 *   npm run icons
 */
import { readFileSync, writeFileSync } from 'node:fs';

const VERSION = '16.38.1';
const types = readFileSync(new URL('../src/data/types.ts', import.meta.url), 'utf8');
const block = types.slice(types.indexOf('SKILL_ICONS = ['), types.indexOf('] as const'));
const slugs = [...block.matchAll(/'([a-z0-9]+)'/g)].map((match) => match[1]);
if (!slugs.length) throw new Error('No SKILL_ICONS found in src/data/types.ts');

const symbols = [];
for (const slug of slugs) {
  const response = await fetch(`https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}/icons/${slug}.svg`);
  if (!response.ok) throw new Error(`${slug}: HTTP ${response.status}`);
  const svg = await response.text();
  const path = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!path) throw new Error(`${slug}: no path in the SVG`);
  symbols.push(`  <symbol id="${slug}" viewBox="0 0 24 24"><path d="${path}"/></symbol>`);
}

const sprite = [
  '<svg xmlns="http://www.w3.org/2000/svg">',
  `  <!-- Simple Icons ${VERSION} (CC0-1.0), generated by scripts/skill-icons.mjs.`,
  '       The logos are trademarks of their respective owners. -->',
  ...symbols,
  '</svg>',
  '',
].join('\n');

writeFileSync(new URL('../public/skills.svg', import.meta.url), sprite);
console.log(`public/skills.svg: ${slugs.length} icons, ${(sprite.length / 1024).toFixed(1)} KB`);
